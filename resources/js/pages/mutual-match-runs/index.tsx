import { Head, Link } from '@inertiajs/react';

type Run = {
    id: number;
    algorithm_version: string;
    input_count: number;
    candidate_count: number;
    generated_at: string | null;
    cycle: { id: number; name: string } | null;
    service: { id: number; code: string; name: string } | null;
    creator: { id: number; name: string } | null;
};

type PaginationLink = {
    url: string | null;
    label: string;
    active: boolean;
};

type Props = {
    runs: {
        data: Run[];
        links: PaginationLink[];
        total: number;
    };
};

export default function MutualMatchRunsIndex({ runs }: Props) {
    return (
        <>
            <Head title="Saved Matching Runs" />

            <div className="space-y-6 p-4 md:p-6">
                <div>
                    <Link
                        href="/mutual-transfers"
                        className="text-sm font-medium text-blue-700 hover:underline dark:text-blue-400"
                    >
                        ← Back to matching preview
                    </Link>

                    <h1 className="mt-3 text-2xl font-semibold text-gray-900 dark:text-gray-100">
                        Saved Matching Runs
                    </h1>

                    <p className="mt-1 text-sm text-gray-600 dark:text-gray-400">
                        Total saved runs: {runs.total}
                    </p>
                </div>

                <div className="rounded-lg border border-gray-200 bg-white shadow-sm dark:border-gray-700 dark:bg-gray-900">
                    {runs.data.length === 0 ? (
                        <p className="p-5 text-sm text-gray-600 dark:text-gray-400">
                            No matching runs have been saved yet.
                        </p>
                    ) : (
                        <div className="overflow-x-auto">
                            <table className="min-w-full text-left text-sm">
                                <thead className="bg-gray-50 text-gray-700 dark:bg-gray-800 dark:text-gray-200">
                                    <tr>
                                        <th className="px-4 py-3">Run</th>
                                        <th className="px-4 py-3">Cycle</th>
                                        <th className="px-4 py-3">Service</th>
                                        <th className="px-4 py-3">Inputs</th>
                                        <th className="px-4 py-3">Candidates</th>
                                        <th className="px-4 py-3">Generated by</th>
                                        <th className="px-4 py-3">Date</th>
                                        <th className="px-4 py-3">Action</th>
                                    </tr>
                                </thead>

                                <tbody className="divide-y divide-gray-200 text-gray-900 dark:divide-gray-700 dark:text-gray-100">
                                    {runs.data.map((run) => (
                                        <tr key={run.id}>
                                            <td className="px-4 py-3">#{run.id}</td>
                                            <td className="px-4 py-3">{run.cycle?.name ?? '—'}</td>
                                            <td className="px-4 py-3">{run.service?.name ?? '—'}</td>
                                            <td className="px-4 py-3">{run.input_count}</td>
                                            <td className="px-4 py-3">{run.candidate_count}</td>
                                            <td className="px-4 py-3">{run.creator?.name ?? '—'}</td>
                                            <td className="px-4 py-3">{run.generated_at ?? '—'}</td>

                                            <td className="px-4 py-3">
                                                <Link
                                                    href={`/mutual-match-runs/${run.id}`}
                                                    className="font-medium text-blue-700 hover:underline dark:text-blue-400"
                                                >
                                                    View
                                                </Link>
                                            </td>
                                        </tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    )}

                    {runs.links.length > 3 && (
                        <div className="flex flex-wrap gap-2 border-t border-gray-200 p-4 dark:border-gray-700">
                            {runs.links.map((link, index) => {
                                const label = link.label
                                    .replace('&laquo;', '«')
                                    .replace('&raquo;', '»');

                                return link.url ? (
                                    <Link
                                        key={index}
                                        href={link.url}
                                        className={`rounded border px-3 py-1 text-sm ${
                                            link.active
                                                ? 'border-blue-700 bg-blue-700 text-white'
                                                : 'border-gray-300 text-gray-700 dark:border-gray-600 dark:text-gray-200'
                                        }`}
                                    >
                                        {label}
                                    </Link>
                                ) : (
                                    <span
                                        key={index}
                                        className="rounded border border-gray-200 px-3 py-1 text-sm text-gray-400 dark:border-gray-700"
                                    >
                                        {label}
                                    </span>
                                );
                            })}
                        </div>
                    )}
                </div>
            </div>
        </>
    );
}
