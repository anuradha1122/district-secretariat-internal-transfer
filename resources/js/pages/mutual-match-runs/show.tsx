import { Head, Link } from '@inertiajs/react';

type Applicant = {
    id: number;
    reference_no: string | null;
    name: string | null;
    post: string | null;
    grade: string | null;
    office: {
        id: number;
        code: string;
        name: string;
    } | null;
};

type Candidate = {
    application_a: Applicant;
    application_b: Applicant;
    rank_a: number;
    rank_b: number;
    score: number;
    worst_rank: number;
    suggestion: 'proposed' | 'conflict';
};

type Run = {
    id: number;
    algorithm_version: string;
    input_count: number;
    candidate_count: number;
    generated_at: string | null;
    cycle: { id: number; name: string } | null;
    service: { id: number; code: string; name: string } | null;
    creator: { id: number; name: string } | null;
    candidates: Candidate[];
};

function ApplicantDetails({
    applicant,
    rank,
}: {
    applicant: Applicant;
    rank: number;
}) {
    return (
        <div>
            <p className="font-medium text-gray-900 dark:text-gray-100">
                {applicant.name ?? '—'}
            </p>

            <p className="mt-1 text-xs text-gray-500 dark:text-gray-400">
                {applicant.reference_no ?? '—'}
            </p>

            <p className="mt-2 text-sm text-gray-700 dark:text-gray-200">
                Office: {applicant.office?.name ?? '—'}
            </p>

            <p className="mt-1 text-sm text-gray-700 dark:text-gray-200">
                Preference rank: {rank}
            </p>
        </div>
    );
}

export default function MutualMatchRunShow({ run }: { run: Run }) {
    return (
        <>
            <Head title={`Matching Run ${run.id}`} />

            <div className="space-y-6 p-4 md:p-6">
                <div>
                    <Link
                        href="/mutual-match-runs"
                        className="text-sm font-medium text-blue-700 hover:underline dark:text-blue-400"
                    >
                        ← Back to saved runs
                    </Link>

                    <h1 className="mt-3 text-2xl font-semibold text-gray-900 dark:text-gray-100">
                        Matching Run #{run.id}
                    </h1>

                    <p className="mt-1 text-sm text-gray-600 dark:text-gray-400">
                        {run.cycle?.name ?? '—'} · {run.service?.name ?? '—'}
                    </p>

                    <p className="mt-1 text-sm text-gray-600 dark:text-gray-400">
                        Generated by {run.creator?.name ?? '—'} on{' '}
                        {run.generated_at ?? '—'}
                    </p>

                    <p className="mt-1 text-xs text-gray-500 dark:text-gray-400">
                        Algorithm: {run.algorithm_version} · Inputs: {run.input_count}
                    </p>
                </div>

                <div className="rounded-md bg-amber-50 p-4 text-sm text-amber-900 dark:bg-amber-950 dark:text-amber-200">
                    This is a saved snapshot. Applications or eligibility may
                    have changed since it was generated. No pair is confirmed.
                </div>

                {run.candidates.length === 0 ? (
                    <div className="rounded-lg border border-gray-200 bg-white p-5 text-sm text-gray-600 dark:border-gray-700 dark:bg-gray-900 dark:text-gray-400">
                        No candidate pairs were found in this run.
                    </div>
                ) : (
                    <div className="space-y-4">
                        {run.candidates.map((candidate) => (
                            <div
                                key={`${candidate.application_a.id}-${candidate.application_b.id}`}
                                className="rounded-lg border border-gray-200 bg-white p-5 shadow-sm dark:border-gray-700 dark:bg-gray-900"
                            >
                                <div className="flex flex-wrap items-center justify-between gap-2">
                                    <span className="text-sm font-semibold text-gray-900 dark:text-gray-100">
                                        {candidate.suggestion === 'proposed'
                                            ? 'Proposed pair'
                                            : 'Conflict alternative'}
                                    </span>

                                    <span className="text-sm text-gray-700 dark:text-gray-200">
                                        Score: {candidate.score}
                                    </span>
                                </div>

                                <div className="mt-4 grid gap-5 md:grid-cols-2">
                                    <ApplicantDetails
                                        applicant={candidate.application_a}
                                        rank={candidate.rank_a}
                                    />

                                    <ApplicantDetails
                                        applicant={candidate.application_b}
                                        rank={candidate.rank_b}
                                    />
                                </div>
                            </div>
                        ))}
                    </div>
                )}
            </div>
        </>
    );
}
